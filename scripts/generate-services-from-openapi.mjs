import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

function readSpec(specPath) {
  const absolutePath = resolve(specPath);
  return JSON.parse(readFileSync(absolutePath, "utf8"));
}

function toCamelCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((segment, index) => {
      const lower = segment.toLowerCase();
      if (index === 0) {
        return lower;
      }
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join("");
}

function renderGeneratedEndpoints(taskServices, actionEndpoints) {
  const taskLines = taskServices.map((service) => `  "${service}",`);
  const actionLines = actionEndpoints.map(
    ({ key, method }) => `  { key: "${key}", method: "${method}" },`,
  );

  return `// Auto-generated by scripts/generate-services-from-openapi.mjs
// Do not edit this file manually.

import type { ActionEndpointConfig } from "../types.js";

export const GENERATED_TASK_SERVICES = [
${taskLines.join("\n")}
] as const;

export const GENERATED_ACTION_ENDPOINTS: ReadonlyArray<ActionEndpointConfig> = [
${actionLines.join("\n")}
];
`;
}

function renderServices(taskServices, actionEndpoints) {
  const taskProps = taskServices.map((service) => {
    const prop = toCamelCase(service);
    return `  readonly ${prop}: FusionTaskResource<"${service}">;`;
  });

  const taskAssignments = taskServices.map((service) => {
    const prop = toCamelCase(service);
    return `    ${prop}: client.task("${service}"),`;
  });

  const actionsByGroup = new Map();
  for (const { key } of actionEndpoints) {
    const [service, ...actionParts] = key.split("/");
    const group = toCamelCase(service);
    const actionName = toCamelCase(actionParts.join("/"));
    if (!actionsByGroup.has(group)) {
      actionsByGroup.set(group, []);
    }
    actionsByGroup.get(group).push({ key, actionName });
  }

  const sortedGroups = [...actionsByGroup.entries()].sort(([a], [b]) =>
    a.localeCompare(b),
  );

  const actionProps = sortedGroups.map(([group, items]) => {
    const itemLines = items
      .sort((a, b) => a.actionName.localeCompare(b.actionName))
      .map(
        ({ key, actionName }) =>
          `    readonly ${actionName}: ActionInvoker<"${key}">;`,
      )
      .join("\n");
    return `  readonly ${group}: {\n${itemLines}\n  };`;
  });

  const actionAssignments = sortedGroups.map(([group, items]) => {
    const itemLines = items
      .sort((a, b) => a.actionName.localeCompare(b.actionName))
      .map(
        ({ key, actionName }) =>
          `      ${actionName}: createActionInvoker(client, "${key}"),`,
      )
      .join("\n");
    return `    ${group}: {\n${itemLines}\n    },`;
  });

  return `// Auto-generated by scripts/generate-services-from-openapi.mjs
// Do not edit this file manually.

import type {
  ActionCallOptions,
  ActionRequest,
  ActionResponsePayload,
} from "./types.js";
import type { FusionClient, FusionTaskResource } from "./client.js";

export type ActionInvoker<TKey extends string> = (
  request?: ActionRequest<TKey>,
  options?: ActionCallOptions,
) => Promise<ActionResponsePayload<TKey>>;

export interface FusionTaskShortcutProperties {
${taskProps.join("\n")}
}

export interface FusionActionShortcutProperties {
${actionProps.join("\n")}
}

function createActionInvoker<TKey extends string>(
  client: FusionClient,
  key: TKey,
): ActionInvoker<TKey> {
  return (request, options) => client.action(key, request, options);
}

export function createTaskShortcuts(
  client: FusionClient,
): FusionTaskShortcutProperties {
  return {
${taskAssignments.join("\n")}
  };
}

export function createActionShortcuts(
  client: FusionClient,
): FusionActionShortcutProperties {
  return {
${actionAssignments.join("\n")}
  };
}
`;
}

function main() {
  const specPath = process.argv[2] ?? "./openapi.full.snapshot.json";

  const spec = readSpec(specPath);
  const paths = spec.paths ?? {};
  const taskServices = new Set();
  const actionEndpoints = [];

  for (const [path, methods] of Object.entries(paths)) {
    const submitMatch = path.match(/^\/v1\/([^/]+)\/submit$/);
    if (submitMatch) {
      taskServices.add(submitMatch[1]);
    }

    const actionMatch = path.match(/^\/v1\/([^/]+)\/action\/(.+)$/);
    if (!actionMatch) {
      continue;
    }

    for (const [method, operation] of Object.entries(methods)) {
      if (!operation || typeof operation !== "object") {
        continue;
      }

      actionEndpoints.push({
        key: `${actionMatch[1]}/${actionMatch[2]}`,
        method: method.toUpperCase(),
      });
    }
  }

  const sortedTaskServices = [...taskServices].sort((a, b) => a.localeCompare(b));
  const sortedActionEndpoints = actionEndpoints.sort((a, b) =>
    a.key.localeCompare(b.key),
  );

  const projectRoot = resolve(dirname(new URL(import.meta.url).pathname), "..");
  const servicesPath = resolve(projectRoot, "src/services.ts");
  const endpointsPath = resolve(projectRoot, "src/generated/endpoints.ts");

  mkdirSync(dirname(endpointsPath), { recursive: true });
  writeFileSync(
    servicesPath,
    renderServices(sortedTaskServices, sortedActionEndpoints),
    "utf8",
  );
  writeFileSync(
    endpointsPath,
    renderGeneratedEndpoints(sortedTaskServices, sortedActionEndpoints),
    "utf8",
  );
}

main();
